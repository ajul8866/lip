// Package report renders a deterministic Markdown report from stored records.
// It does not call the LLM and escapes HTML in user-controlled fields so the
// report can be opened in a Markdown renderer without script execution.
package report

import (
	"bytes"
	"encoding/json"
	"fmt"
	"html"
	"io"
	"sort"
	"strings"
	"time"

	"github.com/lip-project/lip/internal/store"
)

type Data struct {
	AppName       string
	Project       store.Project
	Assets        []store.Asset
	Findings      []store.Finding
	Tasks         []store.Task
	Approvals     []store.Approval
	GeneratedAt   time.Time
	GeneratedBy   string
	SafeLocalOnly bool
	Disclaimer    string
	MaxConcurrent int
}

func Render(w io.Writer, d Data) error {
	var b strings.Builder
	projectName := text(d.Project.Name)
	fmt.Fprintf(&b, "# %s security assessment report: %s\n\n", text(d.AppName), projectName)
	fmt.Fprintf(&b, "- **Project ID:** `%s`\n", text(d.Project.ID))
	fmt.Fprintf(&b, "- **Generated:** %s\n", d.GeneratedAt.UTC().Format(time.RFC3339))
	fmt.Fprintf(&b, "- **Generated by:** %s\n", text(d.GeneratedBy))
	fmt.Fprintf(&b, "- **Declared assets:** %d\n", len(d.Assets))
	fmt.Fprintf(&b, "- **Findings:** %d\n", len(d.Findings))
	fmt.Fprintf(&b, "- **Safe local-only mode:** %t\n", d.SafeLocalOnly)
	fmt.Fprintf(&b, "- **Autonomy limit:** %d concurrent task(s); active/destructive tasks require approval\n\n", d.MaxConcurrent)
	if d.Disclaimer != "" {
		fmt.Fprintf(&b, "> %s\n\n", text(d.Disclaimer))
	}
	if d.Project.Description != "" {
		fmt.Fprintf(&b, "## Project description\n\n%s\n\n", paragraph(d.Project.Description))
	}

	counts := map[string]int{}
	for _, f := range d.Findings {
		if f.Status == "open" {
			counts[f.Severity]++
		}
	}
	b.WriteString("## Executive summary\n\n")
	severityTitles := map[string]string{"critical": "Critical", "high": "High", "medium": "Medium", "low": "Low", "info": "Info"}
	for _, severity := range []string{"critical", "high", "medium", "low", "info"} {
		fmt.Fprintf(&b, "| %s | %d |\n", severityTitles[severity], counts[severity])
	}
	b.WriteString("\n")

	b.WriteString("## Declared assets\n\n")
	if len(d.Assets) == 0 {
		b.WriteString("_No assets were declared._\n\n")
	} else {
		b.WriteString("| Kind | Value | Source | First seen |\n|---|---|---|---|\n")
		for _, a := range d.Assets {
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n",
				cell(a.Kind), cell(a.Value), cell(a.Source), a.FirstSeen.UTC().Format(time.RFC3339))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Findings\n\n")
	if len(d.Findings) == 0 {
		b.WriteString("_No findings recorded._\n\n")
	} else {
		for i, f := range d.Findings {
			fmt.Fprintf(&b, "### %d. [%s] %s\n\n", i+1, strings.ToUpper(text(f.Severity)), text(f.Title))
			fmt.Fprintf(&b, "- **Status:** %s\n- **Source:** %s\n- **Recorded:** %s\n",
				text(f.Status), text(f.Source), f.CreatedAt.UTC().Format(time.RFC3339))
			if f.TaskID != nil {
				fmt.Fprintf(&b, "- **Task:** `%s`\n", text(*f.TaskID))
			}
			fmt.Fprintf(&b, "\n%s\n\n", paragraph(f.Description))
			if len(f.Evidence) > 0 && string(f.Evidence) != "{}" {
				b.WriteString("Evidence:\n\n")
				writeIndentedJSON(&b, f.Evidence)
				b.WriteString("\n")
			}
		}
	}

	b.WriteString("## Tasks\n\n")
	if len(d.Tasks) == 0 {
		b.WriteString("_No tasks recorded._\n\n")
	} else {
		b.WriteString("| Status | Risk | Tool | Title | Created |\n|---|---|---|---|---|\n")
		for _, t := range d.Tasks {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n",
				cell(t.Status), cell(t.RiskLevel), cell(t.Tool), cell(t.Title),
				t.CreatedAt.UTC().Format(time.RFC3339))
		}
		b.WriteString("\n")
	}

	// Sort approvals for stable output even if the caller's slice is unordered.
	approvals := append([]store.Approval(nil), d.Approvals...)
	sort.SliceStable(approvals, func(i, j int) bool { return approvals[i].CreatedAt.After(approvals[j].CreatedAt) })
	b.WriteString("## Approval decisions\n\n")
	if len(approvals) == 0 {
		b.WriteString("_No approval decisions recorded._\n\n")
	} else {
		b.WriteString("| Status | Action | Task | Reason | Created |\n|---|---|---|---|---|\n")
		for _, a := range approvals {
			fmt.Fprintf(&b, "| %s | %s | `%s` | %s | %s |\n",
				cell(a.Status), cell(a.Action), cell(a.TaskID), cell(a.Reason),
				a.CreatedAt.UTC().Format(time.RFC3339))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Methodology and limitations\n\n")
	b.WriteString("LIP records analyst-declared assets, model-drafted tasks and findings, and human approval decisions. ")
	b.WriteString("Model output is untrusted draft material and must be independently validated. ")
	b.WriteString("This MVP does not exploit vulnerabilities, and active actions are limited to the built-in tool catalog behind an approval gate. ")
	b.WriteString("Absence of a finding is not evidence of absence.\n")

	_, err := io.WriteString(w, b.String())
	return err
}

var markdownEscaper = strings.NewReplacer(
	`\`, `\\`,
	"`", "\\`",
	"*", "\\*",
	"_", "\\_",
	"[", "\\[",
	"]", "\\]",
	"(", "\\(",
	")", "\\)",
	"#", "\\#",
	"!", "\\!",
	"|", `\|`,
)

func text(s string) string {
	return markdownEscaper.Replace(html.EscapeString(strings.TrimSpace(s)))
}

func paragraph(s string) string {
	escaped := markdownEscaper.Replace(html.EscapeString(strings.TrimSpace(s)))
	lines := strings.Split(escaped, "\n")
	for i := range lines {
		lines[i] = strings.TrimSpace(lines[i])
	}
	return strings.Join(lines, "\n")
}

func cell(s string) string {
	return text(strings.ReplaceAll(strings.TrimSpace(s), "\n", " "))
}

func writeIndentedJSON(b *strings.Builder, raw []byte) {
	var pretty []byte
	var v any
	if json.Unmarshal(raw, &v) == nil {
		var buf bytes.Buffer
		encoder := json.NewEncoder(&buf)
		encoder.SetEscapeHTML(false)
		encoder.SetIndent("", "  ")
		if encoder.Encode(v) == nil {
			pretty = bytes.TrimRight(buf.Bytes(), "\n")
		}
	}
	if len(pretty) == 0 {
		pretty = raw
	}
	escaped := html.EscapeString(string(pretty))
	for _, line := range strings.Split(escaped, "\n") {
		b.WriteString("    ")
		b.WriteString(line)
		b.WriteByte('\n')
	}
}
